export function translateCropName(nameOrId, lang = "en") {
  if (!nameOrId) return "";
  const key = String(nameOrId).toLowerCase().trim();
  const found = CROP_TRANSLATIONS[key];
  if (found) return found.name[lang] || found.name.en;
  for (const item of Object.values(CROP_TRANSLATIONS)) {
    if (
      item.name.es.toLowerCase() === key ||
      item.name.en.toLowerCase() === key
    ) {
      return item.name[lang] || item.name.en;
    }
  }
  return nameOrId;
}

export function translateCropGroup(group, lang = "en") {
  if (!group) return "";
  for (const item of Object.values(CROP_TRANSLATIONS)) {
    if (item.group.es === group || item.group.en === group) {
      return item.group[lang] || item.group.en;
    }
  }
  return group;
}

export function translateReason(reason, lang = "en") {
  if (!reason || lang === "es") return reason;
  if (reason.includes("Repite el cultivo anterior")) {
    return "Repeats previous crop.";
  }
  if (reason.includes("Comparte la familia")) {
    const match = reason.match(/Comparte la familia (\w+) con (.+)\.?/);
    if (match) {
      const cropName = translateCropName(
        match[2].replace(".", "").trim(),
        "en",
      );
      return `Shares the ${match[1]} family with ${cropName}.`;
    }
    return "Shares the same botanical family with previous crop.";
  }
  if (reason.includes("pertenece a")) {
    const match = reason.match(
      /(.+) pertenece a (\w+), una familia diferente de (.+) \((\w+)\)\.?/,
    );
    if (match) {
      const c1 = translateCropName(match[1].trim(), "en");
      const c2 = translateCropName(match[3].trim(), "en");
      return `${c1} belongs to ${match[2]}, a different family from ${c2} (${match[4]}).`;
    }
  }
  return reason;
}

export function translateRequirement(req, lang = "en") {
  if (!req) return "";
  const item = REQUIREMENT_TRANSLATIONS[req];
  if (item) return item[lang] || item.en;
  return req;
}

export function translateWarning(w, lang = "en") {
  if (!w || lang === "es") return w;
  for (const item of WARNING_TRANSLATIONS) {
    if (item.regex.test(w)) {
      return item[lang] || item.en;
    }
  }
  // Check daily data warning pattern: e.g. "T2M: 2 de 30 días sin datos válidos. No se rellenaron."
  const dayMatch = w.match(
    /^(\w+):\s*(\d+)\s+de\s+(\d+)\s+días sin datos válidos\.\s*No se rellenaron\./,
  );
  if (dayMatch) {
    return `${dayMatch[1]}: ${dayMatch[2]} of ${dayMatch[3]} days without valid data. Not interpolated.`;
  }
  return w;
}

export function translateRule(rule, lang = "en") {
  if (!rule) return rule;
  const tRule = RULES_TRANSLATIONS[rule.id];
  return {
    ...rule,
    text: tRule ? tRule[lang] || rule.text : rule.text,
  };
}

